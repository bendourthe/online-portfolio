import { readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const projectRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const sourcePaths = [
    "content/skills/content/images/writing-communication/technical_communication_workflow.html",
    "content/skills/content/images/leadership-management/leadership_cycle.html"
];

const embeddedSources = {};

for (const sourcePath of sourcePaths) {
    const source = await readFile(resolve(projectRoot, sourcePath));
    embeddedSources[sourcePath] = source.toString("base64");
}

const generatedFile = [
    "/* Generated by js/generate-skills-source-artwork.mjs. Do not edit directly. */",
    "window.SKILLS_SOURCE_ARTWORK = Object.freeze(" + JSON.stringify(embeddedSources, null, 4) + ");",
    ""
].join("\n");

await writeFile(resolve(projectRoot, "js/skills-source-artwork.js"), generatedFile, "utf8");
